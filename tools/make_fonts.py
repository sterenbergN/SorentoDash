"""Generate antialiased VLW fonts (LovyanGFX smooth fonts) from Inter.

usage: python tools/make_fonts.py   ->  writes Fonts.h next to the sketch

Inter is OFL-licensed (https://github.com/rsms/inter).
"""
import os
import struct
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
TTF = os.path.join(HERE, "Inter.ttf")
OUT = os.path.join(HERE, "..", "Fonts.h")

ASCII = "".join(chr(c) for c in range(32, 127)) + "°"  # plus degree sign

# name, pixel size, weight, characters
FONTS = [
    ("FONT_TITLE", 30, 700, ASCII),
    ("FONT_BODY", 18, 600, ASCII),
    ("FONT_SMALL", 13, 600, ASCII),
    ("FONT_HUGE", 60, 700, "0123456789%-.,°"),
]


def build_vlw(size, weight, chars):
    font = ImageFont.truetype(TTF, size)
    font.set_variation_by_axes([min(max(size, 14), 32), weight])
    ascent, descent = font.getmetrics()

    metrics, bitmaps = [], []
    chars = "".join(sorted(set(chars)))  # LovyanGFX binary-searches glyphs
    for ch in chars:
        adv = round(font.getlength(ch))
        x0, y0, x1, y1 = font.getbbox(ch, anchor="ls")
        w, h = max(0, x1 - x0), max(0, y1 - y0)
        if ch == " " or w == 0 or h == 0:
            metrics.append((ord(ch), 0, 0, adv, 0, 0))
            bitmaps.append(b"")
            continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-x0, -y0), ch, font=font, fill=255, anchor="ls")
        # unicode, height, width, xAdvance, dY (top above baseline), dX
        metrics.append((ord(ch), h, w, adv, -y0, x0))
        bitmaps.append(img.tobytes())

    out = struct.pack(">6i", len(chars), 11, size, 0, ascent, descent)
    for m in metrics:
        out += struct.pack(">7i", *m, 0)
    for b in bitmaps:
        out += b
    return out


def main():
    lines = [
        "// Generated by tools/make_fonts.py from Inter (OFL). Do not edit.",
        "#pragma once",
        "#include <stdint.h>",
        "",
    ]
    for name, size, weight, chars in FONTS:
        data = build_vlw(size, weight, chars)
        lines.append(f"// {size}px weight {weight}, {len(chars)} glyphs, {len(data)} bytes")
        lines.append(f"const uint8_t {name}[] = {{")
        for i in range(0, len(data), 24):
            lines.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        lines.append("};")
        lines.append("")
        print(f"{name}: {len(data)} bytes")
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main()
